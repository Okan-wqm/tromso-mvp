// Builds the islands' icon set, frontend/islands/ui/icon-shapes.ts, from the one icon source, templates/icons/*.svg (the
// Lucide-style outlines the server-rendered pages include with templates/icons/_icon.html). An icon is data, a list of
// [element, attributes] the React Icon draws as its own elements: no markup string reaches the page
// (no dangerouslySetInnerHTML), and the server's and the islands' icons can never differ. It also builds static/css/glyphs.css:
// every icon as a mask in a custom property of the new look (--glyph-<name>), for a glyph the page's CSS draws without
// markup (the monitoring cards' state glyphs, static/css/monitor-next.css, a class a script sets included).
//   node scripts/icons.mjs          write it (npm run build:icons, part of npm run build)
//   node scripts/icons.mjs --check  fail when either is not what the templates' icons build now (npm test runs it)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'templates', 'icons');
const TARGET = join(ROOT, 'frontend', 'islands', 'ui', 'icon-shapes.ts');
const GLYPHS = join(ROOT, 'static', 'css', 'glyphs.css');
const ELEMENTS = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const ATTRIBUTES = new Set(['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'x2', 'y1', 'y2', 'width', 'height', 'points', 'fill']);

export function shapes(svg, name) {
  const found = [];
  const rest = svg.replace(/<(\w+)((?:\s+[\w-]+="[^"]*")*)\s*\/?>(?:<\/\1>)?/g, (_whole, tag, attrs) => {
    if (!ELEMENTS.has(tag)) throw new Error(`templates/icons/${name}.svg: <${tag}> is not a shape the islands draw`);
    const pairs = [...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => {
      if (!ATTRIBUTES.has(key)) throw new Error(`templates/icons/${name}.svg: ${key}= is not an attribute the islands draw`);
      return [key, value];
    });
    found.push([tag, Object.fromEntries(pairs)]);
    return '';
  });
  if (rest.trim()) throw new Error(`templates/icons/${name}.svg: unexpected text ${JSON.stringify(rest.trim().slice(0, 40))}`);
  return found;
}

export function build() {
  const names = readdirSync(SOURCE).filter((file) => file.endsWith('.svg')).map((file) => file.slice(0, -4)).sort();
  const lines = [
    '// Generated by scripts/icons.mjs from templates/icons/*.svg: do not edit (npm run build:icons).',
    'export type Shape = readonly [string, Readonly<Record<string, string>>];',
    'export const ICONS = {',
    ...names.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(shapes(readFileSync(join(SOURCE, `${name}.svg`), 'utf8'), name))},`),
    '} as const satisfies Record<string, readonly Shape[]>;',
    'export type IconName = keyof typeof ICONS;',
  ];
  return `${lines.join('\n')}\n`;
}

/** static/css/glyphs.css: each icon as a mask image in a custom property of the new look, drawn as the icons are drawn
 *  (24 units, a 1.75-unit round stroke, app.css `.icon`). Its paint is the SVG's own currentColor, which a mask reads
 *  only for its alpha: the page paints the glyph in its own colour (background: currentColor under the mask). Encoded so
 *  that no character of the outline can end the url() early. */
export function glyphs() {
  const names = readdirSync(SOURCE).filter((file) => file.endsWith('.svg')).map((file) => file.slice(0, -4)).sort();
  const encode = (text) => encodeURIComponent(text).replace(/[()'!*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`);
  const lines = [
    '/* Generated by scripts/icons.mjs from templates/icons/*.svg: do not edit (npm run build:icons). Each icon as a mask',
    '   (--glyph-<name>), for a glyph drawn by CSS alone: mask: var(--glyph-<name>); background: currentColor. */',
    '[data-ui="next"] {',
    ...names.map((name) => {
      const body = readFileSync(join(SOURCE, `${name}.svg`), 'utf8').trim();
      shapes(body, name);                                  // the same refusals as the islands' set
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
      return `  --glyph-${name}: url("data:image/svg+xml,${encode(svg)}");`;
    }),
    '}',
    '/* A shape drawn as an icon: an element of the new look that names its icon in --glyph (static/css/monitor-next.css,',
    "   the monitoring cards' state shapes), painted in its own colour under the mask. Here, beside the icons it reads, and",
    "   only where masks are drawn: a page that lacks this sheet, or a browser without masks, keeps the element's own shape",
    "   (the classic look's), never seven identical squares. */",
    '@supports (mask-image: url("")) or (-webkit-mask-image: url("")) {',
    '  html[data-ui="next"] .monitor-shape {',
    '    width: 1em; height: 1em; flex: none; border: 0; border-radius: 0; clip-path: none; background: currentColor;',
    '    -webkit-mask: var(--glyph) center / contain no-repeat; mask: var(--glyph) center / contain no-repeat;',
    '    vertical-align: -.14em;',
    '  }',
    '  @media (forced-colors: active) { html[data-ui="next"] .monitor-shape { forced-color-adjust: none; background: CanvasText; } }',
    '}',
  ];
  return `${lines.join('\n')}\n`;
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  const built = [[TARGET, build(), 'frontend/islands/ui/icon-shapes.ts'], [GLYPHS, glyphs(), 'static/css/glyphs.css']];
  if (process.argv.includes('--check')) {
    for (const [path, text, name] of built) {
      let now = '';
      try { now = readFileSync(path, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing: stale */ }
      if (now !== text) {
        process.stderr.write(`${name} is not what templates/icons builds: run \`npm run build:icons\`.\n`);
        process.exit(1);
      }
    }
    process.stdout.write('icon-shapes.ts and glyphs.css are what templates/icons builds.\n');
  } else {
    for (const [path, text] of built) writeFileSync(path, text);
  }
}
