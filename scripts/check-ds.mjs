// The design-system gate (docs/design/system/README.md, "The gate"): fails on a one-off style.
//   node scripts/check-ds.mjs                 check (npm run check:ds; CI runs it, and npm test runs it too)
//   node scripts/check-ds.mjs --write         write today's counts into the ratchet (only after they went down)
//   node scripts/check-ds.mjs --root <dir>    check another tree (the gate's own test plants faults in one)
// It fails when
//   1. a stylesheet writes a colour (a hex, rgb(), hsl(), a named colour) anywhere but tokens.css;
//   2. the component layer, static/css/ds.css, writes a raw font size or radius (it reads only tokens);
//   3. a stylesheet has MORE raw font sizes or radii (px or rem, not a token) than the ratchet allows for it;
//   4. the templates use an old class name of a pattern (button, data-table, badge, tabs, ...) MORE often than the
//      ratchet allows, or an arbitrary Tailwind size (tw:text-[13px]) more often;
//   5. a count went DOWN without the ratchet being lowered with it (so it can never creep back up unseen);
//   6. a template that loads base.css does not load ds.css next (after base.css and ui.css, before app.css, components.css,
//      a page's own sheets and tw.css): the pattern sheet is the default, and a rule of a later sheet for one element of a
//      pattern wins by coming later (loaded after them, the rail's collapse button, the printed report's Print button and
//      tables and a status chip's size all lost to it: review of slice 1a, findings 1 and 6).
// The ratchet is docs/design/system/ds-ratchet.json. tokens.css (the tokens themselves), tw.css (built from the token
// theme) and card-grid.css (generated by manage.py card_grid_css) are not read.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const at = args.indexOf('--root');
const ROOT = at >= 0 ? resolve(args[at + 1]) : resolve(dirname(fileURLToPath(import.meta.url)), '..');
const RATCHET = join(ROOT, 'docs', 'design', 'system', 'ds-ratchet.json');
const CSS = join(ROOT, 'static', 'css');
const SKIP = new Set(['tokens.css', 'tw.css', 'card-grid.css']);
const COMPONENTS = 'ds.css';

// The old class names of the eight patterns, each mapped onto its ui-* rule set in ds.css; their uses only go down.
export const LEGACY = ['button', 'button-inline', 'button-ghost', 'button-danger', 'data-table', 'table-wrap', 'badge',
  'tabs', 'tab', 'view-tabs', 'view-tab', 'view-count', 'toolbar', 'filter-bar', 'filter-button', 'card', 'tile', 'calc-card'];
const NAMED = /(?<![-\w])(?:white|black|red|green|blue|yellow|orange|purple|pink|gray|grey|silver|maroon|navy|teal|olive|lime|aqua|fuchsia)(?![-\w])/i;
const COLOUR = /#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch)\(/;

const strip = (css) => css.replace(/\/\*[\s\S]*?\*\//g, (c) => c.replace(/[^\n]/g, ' '));
const raw = (value) => /(?<![\w.-])\d*\.?\d+(?:px|rem)\b/.test(value.replace(/var\([^()]*\)/g, ''));

function declarations(css) {
  // [line, property, value] of every declaration (comments blanked, so line numbers stay right)
  const found = [];
  const text = strip(css);
  for (const match of text.matchAll(/([a-z-]+)\s*:\s*([^;{}]+)(?=[;}])/g)) {
    const line = text.slice(0, match.index).split('\n').length;
    found.push([line, match[1], match[2].trim()]);
  }
  return found;
}

export function scanCss(name, css) {
  const result = { colours: [], fontSizes: [], radii: [] };
  for (const [line, property, value] of declarations(css)) {
    const where = `${name}:${line} ${property}: ${value}`;
    // an @supports condition only asks the browser what it can parse; url() may name a file
    const painted = value.replace(/url\([^)]*\)/g, '');
    if (COLOUR.test(painted) || (NAMED.test(painted) && !/^(?:font|grid|content|counter|list-style|animation|transition)/.test(property))) {
      result.colours.push(where);
    }
    if ((property === 'font-size' || property === 'font') && raw(value)) result.fontSizes.push(where);
    if (/^border(?:-[a-z]+)*-radius$/.test(property) && raw(value)) result.radii.push(where);
  }
  return result;
}

function templateFiles() {
  const roots = [join(ROOT, 'templates')];
  for (const entry of existsSync(ROOT) ? readdirSync(ROOT) : []) {
    const candidate = join(ROOT, entry, 'templates');
    if (!['node_modules', '.venv', '.git'].includes(entry) && existsSync(candidate)) roots.push(candidate);
  }
  const files = [];
  const walk = (dir) => {
    if (!existsSync(dir)) return;
    for (const name of readdirSync(dir)) {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) walk(path);
      else if (name.endsWith('.html')) files.push(path);
    }
  };
  for (const dir of [...new Set(roots)]) walk(dir);
  return files;
}

export function scanTemplate(html) {
  const counts = {};
  let arbitrary = 0;
  const bare = html.replace(/\{%.*?%\}|\{\{.*?\}\}|\{#.*?#\}/gs, ' ');
  for (const match of bare.matchAll(/\bclass="([^"]*)"/g)) {
    for (const token of match[1].split(/\s+/)) {
      if (LEGACY.includes(token)) counts[token] = (counts[token] ?? 0) + 1;
      if (/^tw:.*\[[^\]]*\d(?:px|rem)\b[^\]]*\]$/.test(token)) arbitrary += 1;
    }
  }
  return { counts, arbitrary };
}

// The style sheets a template links, in the order it links them (a comment may name a sheet: it links nothing).
export function sheetOrder(html) {
  const bare = html.replace(/\{#.*?#\}/gs, ' ').replace(/\{% comment %\}.*?\{% endcomment %\}/gs, ' ');
  return [...bare.matchAll(/<link[^>]*css\/([\w-]+)\.css/g)].map((match) => match[1]);
}

// What is wrong with the order of the sheets a template links (nothing, when it does not link base.css: a page that only adds a sheet).
export function orderProblems(html) {
  const order = sheetOrder(html);
  if (!order.includes('base')) return [];
  const at = order.indexOf('ds');
  if (at < 0) return ['loads base.css but not ds.css, the pattern sheet'];
  const early = new Set(['fonts', 'tokens', 'base', 'ui']);
  const late = order.slice(0, at).filter((name) => !early.has(name));
  const before = order.slice(at + 1).filter((name) => early.has(name));
  return [...late.map((name) => `${name}.css comes before ds.css: a rule of it for one element of a pattern would lose to the pattern`),
    ...before.map((name) => `${name}.css comes after ds.css`)];
}

export function measure() {
  const css = {};
  const colours = [];
  const component = [];
  for (const name of existsSync(CSS) ? readdirSync(CSS).filter((file) => file.endsWith('.css')).sort() : []) {
    if (SKIP.has(name)) continue;
    const found = scanCss(name, readFileSync(join(CSS, name), 'utf8'));
    colours.push(...found.colours);
    if (name === COMPONENTS) component.push(...found.fontSizes, ...found.radii);
    else css[name] = { fontSizes: found.fontSizes.length, radii: found.radii.length };
  }
  const legacy = Object.fromEntries(LEGACY.map((name) => [name, 0]));
  let arbitrary = 0;
  const order = [];
  for (const file of templateFiles()) {
    const html = readFileSync(file, 'utf8');
    order.push(...orderProblems(html).map((problem) => `${relative(ROOT, file).replaceAll('\\', '/')}: ${problem}`));
    const found = scanTemplate(html);
    for (const [name, count] of Object.entries(found.counts)) legacy[name] += count;
    arbitrary += found.arbitrary;
  }
  return { colours, component, order, counts: { css, legacy, twArbitrarySizes: arbitrary } };
}

function compare(now, allowed) {
  const over = [];
  const under = [];
  const check = (label, count, limit) => {
    if (count > limit) over.push(`${label}: ${count}, the ratchet allows ${limit}`);
    else if (count < limit) under.push(`${label}: ${count}, the ratchet still says ${limit}`);
  };
  for (const [file, { fontSizes, radii }] of Object.entries(now.css)) {
    check(`${file} raw font sizes`, fontSizes, allowed.css?.[file]?.fontSizes ?? 0);
    check(`${file} raw radii`, radii, allowed.css?.[file]?.radii ?? 0);
  }
  for (const file of Object.keys(allowed.css ?? {})) if (!now.css[file]) under.push(`${file}: gone, the ratchet still lists it`);
  for (const [name, count] of Object.entries(now.legacy)) check(`templates: class "${name}"`, count, allowed.legacy?.[name] ?? 0);
  check('templates: arbitrary Tailwind sizes', now.twArbitrarySizes, allowed.twArbitrarySizes ?? 0);
  return { over, under };
}

function main() {
  const now = measure();
  if (args.includes('--write')) {
    writeFileSync(RATCHET, `${JSON.stringify(now.counts, null, 2)}\n`);
    process.stdout.write(`wrote ${relative(ROOT, RATCHET)}\n`);
  }
  const allowed = existsSync(RATCHET) ? JSON.parse(readFileSync(RATCHET, 'utf8')) : {};
  const { over, under } = compare(now.counts, allowed);
  const problems = [
    ...now.colours.map((where) => `a colour outside tokens.css: ${where}`),
    ...now.component.map((where) => `ds.css reads only tokens: ${where}`),
    ...now.order.map((problem) => `the order of the sheets, ds.css first after base.css and ui.css: ${problem}`),
    ...over.map((line) => `up: ${line}`),
    ...under.map((line) => `down, lower the ratchet (node scripts/check-ds.mjs --write): ${line}`),
  ];
  const sum = (key) => Object.values(now.counts.css).reduce((total, file) => total + file[key], 0);
  const legacy = Object.values(now.counts.legacy).reduce((total, count) => total + count, 0);
  process.stdout.write(`design-system gate: ${sum('fontSizes')} raw font sizes and ${sum('radii')} raw radii in the old sheets, `
    + `${legacy} old class names in the templates, ${now.counts.twArbitrarySizes} arbitrary Tailwind sizes\n`);
  if (problems.length) {
    process.stderr.write(`${problems.map((line) => `  ${line}`).join('\n')}\n${problems.length} problem(s)\n`);
    process.exit(1);
  }
  process.stdout.write('no one-off style beyond the ratchet\n');
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) main();
