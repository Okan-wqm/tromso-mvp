"""The deny-list of the browser guard (owner amendment B2: no chemistry in the browser). Writes
chemcore/guard-list.txt from the code that holds the chemistry: the public functions and constants of the Rust
core (chemcore/core/src) and of the chemistry not yet cleared beside it (chemcore/experimental/src, which the
application never reaches, but whose formulas must not reach the browser either) and the names of its Python doors (farm/water/chemistry.py, deffeyes.py, dosing.py,
charts.py: they hold no formula since the retirement audit S10, farm/tests/test_one_formula.py). Two kinds of entry:

  name <identifier>   a function or constant name with an underscore, at least 6 characters (single words such as
                      `draw` or `split` would match ordinary text)
  number <repr>       a numeric literal with at least 5 significant digits (a coefficient: 6320.813, 1.575701e5), not
                      a power of ten (1000.0: a unit's factor)

core/test_no_chemistry_in_browser.py fails when a shipped file holds an entry, and when this file is stale:
    python chemcore/scripts/gen_guard_list.py > chemcore/guard-list.txt
Standard library only."""
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
PYTHON_SOURCES = ['farm/water/chemistry.py', 'farm/water/deffeyes.py', 'farm/water/dosing.py', 'farm/water/charts.py']
RUST_SOURCES = ['chemcore/core/src', 'chemcore/experimental/src']
RUST_ITEM = re.compile(r'\bpub\s+(?:const\s+fn|fn|const|static)\s+([A-Za-z_][A-Za-z0-9_]*)')
RUST_NUMBER = re.compile(r'(?<![A-Za-z0-9_.])(\d[\d_]*\.\d[\d_]*(?:[eE][-+]?\d+)?|\d[\d_]*[eE][-+]?\d+)(?:_?f64)?')


def significant_digits(text):
    """The significant digits of a literal as written: 6320.813 has 7, 1.575701e5 has 7, 0.000232 has 3."""
    mantissa = re.split('[eE]', text.replace('_', '').lstrip('+-'))[0]
    return len(mantissa.replace('.', '').lstrip('0'))


def power_of_ten(value):
    """1000.0, 0.001, 1e6: a unit's factor, no coefficient (frontend redesign, decision 7). On the list, 1000.0 failed every
    bundle a minifier had written a 1e3 into; the coefficients themselves (87.74, 1776.0, 6320.813) stay, trailing zeros
    and all, so the list loses nothing but the powers of ten."""
    return value != 0 and float(f'{abs(value):e}'.split('e')[0]) == 1.0


def distinctive_name(name):
    name = name.lstrip('_')
    return '_' in name and len(name) >= 6, name


def from_python(path):
    names, numbers = set(), set()
    tree = ast.parse(path.read_text(encoding='utf-8'))
    for node in tree.body:
        targets = []
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            targets = [node.name]
        elif isinstance(node, ast.Assign):
            targets = [target.id for target in node.targets if isinstance(target, ast.Name)]
        for target in targets:
            keep, name = distinctive_name(target)
            if keep:
                names.add(name)
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, float):
            source = ast.get_source_segment(path.read_text(encoding='utf-8'), node) or repr(node.value)
            if significant_digits(source) >= 5 and not power_of_ten(node.value):
                numbers.add(node.value)
    return names, numbers


def from_rust(folder):
    names, numbers = set(), set()
    for path in sorted(folder.rglob('*.rs')):
        text = path.read_text(encoding='utf-8')
        for name in RUST_ITEM.findall(text):
            keep, name = distinctive_name(name)
            if keep:
                names.add(name)
        for literal in RUST_NUMBER.findall(text):
            value = float(literal.replace('_', ''))
            if significant_digits(literal) >= 5 and not power_of_ten(value):
                numbers.add(value)
    return names, numbers


def entries(root=ROOT):
    names, numbers = set(), set()
    for folder in RUST_SOURCES:
        more_names, more_numbers = from_rust(root / folder)
        names |= more_names
        numbers |= more_numbers
    for source in PYTHON_SOURCES:
        more_names, more_numbers = from_python(root / source)
        names |= more_names
        numbers |= more_numbers
    return sorted(names), sorted(numbers)


def text(root=ROOT):
    names, numbers = entries(root)
    lines = ['# The browser guard\'s deny-list (owner amendment B2). Generated by chemcore/scripts/gen_guard_list.py;',
             '# never edited by hand. core/test_no_chemistry_in_browser.py fails when it is stale.']
    lines += [f'name {name}' for name in names]
    lines += [f'number {number!r}' for number in numbers]
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    sys.stdout.write(text())
